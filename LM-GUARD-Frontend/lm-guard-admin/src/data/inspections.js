/** Builds the evidence artwork for a product with optional defects applied. */
export function labelFor(productId, defects = {}) {
  const base = LABEL_BASE[productId] || {};
  return packageLabel({ ...base, ...defects });
}

/* Declaration helpers ------------------------------------------------- */
const D = (field, detected, status, confidence) => {
  const meta = DECLARATION_FIELDS.find((f) => f.field === field);
  return {
    field,
    label: meta?.label || field,
    ruleId: meta?.ruleId,
    detected,
    status,
    confidence,
  };
};

const timeline = (date, { verdict = 'NON_COMPLIANT', reviewed = false } = {}) => {
  const t = (offsetSec) => new Date(new Date(date).getTime() + offsetSec * 1000).toISOString();
  const steps = [
    { label: 'Package image received', at: t(0), state: 'done', detail: 'Uploaded from field device' },
    { label: 'OCR extraction completed', at: t(9), state: 'done', detail: 'Text regions resolved on principal display panel' },
    { label: 'Structured facts assembled', at: t(14), state: 'done', detail: '7 declaration fields extracted' },
    { label: 'Ruleset 2026.1 evaluated', at: t(18), state: 'done', detail: '12 active rules applied' },
  ];
  if (verdict === 'COMPLIANT') {
    steps.push({ label: 'No violation detected', at: t(19), state: 'done', detail: 'All mandatory declarations satisfied' });
    steps.push({ label: 'Inspector confirmed compliant', at: t(240), state: 'done', detail: 'Record closed' });
  } else {
    steps.push({
      label: verdict === 'REVIEW_REQUIRED' ? 'Low-confidence finding raised' : 'Potential violation detected',
      at: t(19),
      state: 'alert',
      detail: verdict === 'REVIEW_REQUIRED' ? 'Confidence below decision threshold' : 'Rule condition not satisfied',
    });
    steps.push(
      reviewed
        ? { label: 'Escalated for enforcement', at: t(600), state: 'done', detail: 'Forwarded to zonal controller' }
        : { label: 'Awaiting inspector review', at: null, state: 'pending', detail: 'Human decision required' },
    );
  }
  return steps;
};

